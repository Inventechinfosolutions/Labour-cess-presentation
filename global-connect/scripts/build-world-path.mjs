// Projects world-atlas land into a flat SVG path for the Heritage home maps.
// Run: node scripts/build-world-path.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

const W = 1000;
const H = 470;
const ROTATE = -12;
const frame = {
  type: "MultiPoint",
  coordinates: [
    [-178 - ROTATE, 0],
    [178 - ROTATE, 0],
    [-ROTATE, 78],
    [-ROTATE, -54],
  ],
};
const projection = geoNaturalEarth1().rotate([ROTATE, 0]).fitSize([W, H], frame);
const d = geoPath(projection).digits(1)(land);

const out = `/** Flat world land outline (Natural Earth projection). Generated by scripts/build-world-path.mjs. */
export const WORLD_VIEWBOX = { w: ${W}, h: ${H} };
export const WORLD_PROJECTION = { rotate: ${ROTATE}, scale: ${projection.scale().toFixed(3)}, translate: [${projection
  .translate()
  .map((v) => v.toFixed(2))
  .join(", ")}] as [number, number] };
export const WORLD_LAND_D = ${JSON.stringify(d)};
`;
writeFileSync(new URL("../src/lib/worldPath.ts", import.meta.url), out);
console.log(`${(d.length / 1024).toFixed(1)} KB path`);
