// Samples land points from world-atlas for the Kannadigas hero globe.
// Run: node scripts/build-globe-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

const STEP = 1.25;
const dots = [];
for (let lat = -58; lat <= 80; lat += STEP) {
  const lonStep = STEP / Math.max(0.25, Math.cos((lat * Math.PI) / 180));
  for (let lon = -180; lon < 180; lon += lonStep) {
    if (geoContains(land, [lon, lat])) dots.push(Math.round(lon * 10) / 10, Math.round(lat * 10) / 10);
  }
}

const out = `/** Land sample points as a flat [lon, lat, lon, lat, …] list. Generated by scripts/build-globe-dots.mjs. */
export const GLOBE_DOTS = new Float32Array([${dots.join(",")}]);
`;
writeFileSync(new URL("../src/lib/globeDots.ts", import.meta.url), out);
console.log(`${dots.length / 2} dots`);
